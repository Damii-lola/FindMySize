/**
 * Put the popup customiser onto the GitHub Pages copy of the site (the repo root) without rebuilding it.
 *
 * The repo has two built copies of the site:
 *
 *   web/dist   what the Render server serves, and what an embedded store's popup iframe loads. It is an exact
 *              `vite build` of web/src (default settings), so it is simply rebuilt:   cd web && npm run build
 *
 *   repo root  what GitHub Pages serves (/assets, /dashboard, /size ...). It is an older build that has since been
 *              patched by hand (admin chart loading, de-duplication, pricing text, the Brand field), so a fresh build
 *              copied over it would silently undo those patches. This script changes it in the smallest way instead.
 *
 * The popup's code is kept as plain, readable modules next to embed.js:
 *
 *   /popup-config.js   <- web/src/popup-config.js   (what a popup looks like; used by every page that draws one)
 *   /popup-editor.js   <- web/src/popup-editor.js   (the "Preview & Customise Popup" editor)
 *   /shop-preview.js   <- web/src/shop.js           (the demo store page behind the editor's Button tab)
 *
 * and the built bundles are changed in exactly two small places:
 *
 *   1. assets/popup-config-<hash>.js  becomes a few lines that re-export /popup-config.js under the short names the
 *      other bundles import (dashboard, popup page, shop, preview). Nothing else that imports it changes.
 *   2. assets/dashboard-<hash>.js  opens the editor from /popup-editor.js instead of its built-in one.
 *
 * Run from web/:  npm run deploy:popup
 * It can be run again at any time (after editing web/src), and it stops without writing anything if a place it
 * expects to change is not exactly as expected.
 */
import { copyFileSync, existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const web = join(dirname(fileURLToPath(import.meta.url)), '..');
const repo = join(web, '..');
const read = (p) => readFileSync(p, 'utf8');

const fail = (message) => { console.error(`\nSTOPPED: ${message}\nNothing was changed after this point.`); process.exit(1); };

/** Only the GitHub Pages copy is spliced; web/dist is rebuilt with `npm run build` (see above). */
const TARGETS = [{ name: 'GitHub Pages (repo root)', dir: repo, base: '/FindMySize/' }];

/** The name each deployed bundle uses for each export of popup-config (checked against the built code). */
const ALIASES = {
  D: 'DEFAULTS', F: 'FONTS', a: 'encodeDesign', b: 'buttonAttributeString', c: 'applyPopupConfig', d: 'decodeDesign',
  e: 'effectiveColours', h: 'hex6', n: 'normalizePopup', p: 'popupText', r: 'readableOn',
};

const OPEN_FROM = 'try{kt({chart:e,siteUrl:Ee,toast:J,onSave:';
const OPEN_TO = 'try{import("../popup-editor.js").then(m=>m.openPopupEditor({chart:e,siteUrl:Ee,toast:J,onSave:';
const END_FROM = 'await le()}})}catch(t){console.error("openCustomizer failed:"';
const END_TO = 'await le()}})).catch(t=>{console.error("openCustomizer failed:",t),J("Could not open the customiser.","error")})}catch(t){console.error("openCustomizer failed:"';
const shim = `/* Compatibility layer. The real code is /popup-config.js; this file keeps the short export names
   that the other built bundles import. Generated by web/scripts/deploy-popup-modules.mjs. */
export { ${Object.entries(ALIASES).map(([short, full]) => `${full} as ${short}`).join(', ')} } from '../popup-config.js';
`;

for (const f of ['src/popup-config.js', 'src/popup-editor.js', 'src/shop.js']) if (!existsSync(join(web, f))) fail(`web/${f} is missing`);
if (!existsSync(join(repo, 'embed.js'))) fail('embed.js is missing at the repo root');

/* ---- 1. check every target before touching any ---- */
const plans = TARGETS.map((target) => {
  const assets = join(target.dir, 'assets');
  if (!existsSync(assets)) fail(`${target.name}: ${assets} does not exist`);
  const find = (prefix) => readdirSync(assets).filter((f) => f.startsWith(prefix) && f.endsWith('.js'));
  const [configChunk] = find('popup-config-');
  const [dashboardChunk] = find('dashboard-');
  if (!configChunk || !dashboardChunk) fail(`${target.name}: could not find the popup-config and dashboard bundles`);

  const configPath = join(assets, configChunk);
  const currentConfig = read(configPath);
  const isShim = currentConfig.includes("from '../popup-config.js'");
  if (!isShim) {
    const exported = (/export\{([^}]*)\}/.exec(currentConfig) || [])[1];
    if (!exported) fail(`${target.name}: ${configChunk} has no export list`);
    const names = exported.split(',').map((x) => x.trim().split(' as ').pop()).sort();
    if (names.join(',') !== Object.keys(ALIASES).sort().join(',')) fail(`${target.name}: ${configChunk} exports ${names} but the shim expects ${Object.keys(ALIASES).sort()}`);
  }

  // every bundle that imports popup-config may only ask for names the shim provides
  for (const file of readdirSync(assets).filter((f) => f.endsWith('.js'))) {
    for (const m of read(join(assets, file)).matchAll(/import\{([^}]*)\}from"\.\/popup-config-[A-Za-z0-9_-]+\.js"/g)) {
      for (const part of m[1].split(',')) {
        const name = part.trim().split(' as ')[0];
        if (!ALIASES[name]) fail(`${target.name}: ${file} imports "${name}" from the popup-config bundle, which the shim does not provide`);
      }
    }
  }

  const dashboardPath = join(assets, dashboardChunk);
  const dashboard = read(dashboardPath);
  const patched = dashboard.includes('import("../popup-editor.js")');
  if (!patched) {
    for (const anchor of [OPEN_FROM, END_FROM]) {
      const count = dashboard.split(anchor).length - 1;
      if (count !== 1) fail(`${target.name}: expected to find this once in ${dashboardChunk}, found ${count}: ${anchor.slice(0, 60)}…`);
    }
  }

  const shopHtmlPath = join(target.dir, 'shop', 'index.html');
  const shopHtml = read(shopHtmlPath);
  const shopDone = shopHtml.includes(`${target.base}shop-preview.js`);
  const shopFrom = new RegExp(`<script type="module" crossorigin src="${target.base}assets/shop-[A-Za-z0-9_-]+\\.js"></script>`);
  if (!shopDone && !shopFrom.test(shopHtml)) fail(`${target.name}: shop/index.html does not have the expected shop script tag`);

  return { target, configChunk, configPath, dashboardChunk, dashboardPath, dashboard, patched, shopHtmlPath, shopHtml, shopDone, shopFrom };
});

/* ---- 2. write ---- */
copyFileSync(join(repo, 'embed.js'), join(web, 'public/embed.js'));
for (const plan of plans) {
  const { target } = plan;
  copyFileSync(join(web, 'src/popup-config.js'), join(target.dir, 'popup-config.js'));
  copyFileSync(join(web, 'src/popup-editor.js'), join(target.dir, 'popup-editor.js'));
  copyFileSync(join(web, 'src/shop.js'), join(target.dir, 'shop-preview.js'));
  if (target.dir !== repo) copyFileSync(join(repo, 'embed.js'), join(target.dir, 'embed.js'));
  writeFileSync(plan.configPath, shim);
  if (!plan.patched) writeFileSync(plan.dashboardPath, plan.dashboard.replace(OPEN_FROM, OPEN_TO).replace(END_FROM, END_TO));
  if (!plan.shopDone) {
    writeFileSync(plan.shopHtmlPath, plan.shopHtml.replace(plan.shopFrom, `<script src="${target.base}embed.js"></script>\n    <script type="module" src="${target.base}shop-preview.js"></script>`));
  }
  console.log(`${target.name}`);
  console.log(`  ok  popup-config.js, popup-editor.js, shop-preview.js${target.dir === repo ? '' : ', embed.js'} copied`);
  console.log(`  ok  ${plan.configChunk} re-exports /popup-config.js (${Object.keys(ALIASES).length} names)`);
  console.log(`  ok  ${plan.dashboardChunk} ${plan.patched ? 'already opens' : 'now opens'} /popup-editor.js`);
  console.log(`  ok  shop/index.html ${plan.shopDone ? 'already draws' : 'now draws'} the real embed button`);
}
